async function seedDatabase() {
  let mongoUri = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/careerscope';
  let memoryServer = null;

  try {
    console.log(`Connecting to MongoDB for seeding at: ${mongoUri}`);
    await mongoose.connect(mongoUri, { serverSelectionTimeoutMS: 3000 });
  } catch (err) {
    console.warn('Local MongoDB unavailable. Launching in-memory MongoDB for seeding...');
    try {
      const { MongoMemoryServer } = require('mongodb-memory-server');
      memoryServer = await MongoMemoryServer.create();
      mongoUri = memoryServer.getUri();
      await mongoose.connect(mongoUri);
      console.log(`In-memory MongoDB started at: ${mongoUri}`);
    } catch (memErr) {
      console.error('Failed to start in-memory MongoDB:', memErr.message);
      process.exit(1);
    }
  }

  try {
    console.log('Seeding/upserting courses (without affecting users or other collections)...');
    
    // Upsert courses by name to avoid duplicate records while preserving other collections
    const courseOperations = coursesData.map((course) => ({
      updateOne: {
        filter: { name: course.name },
        update: { $set: course },
        upsert: true,
      },
    }));
    await Course.bulkWrite(courseOperations);
    const totalCourses = await Course.countDocuments();
    console.log(`Successfully seeded/updated courses! Total courses in database: ${totalCourses}`);

    console.log('Seeding/upserting careers...');
    const careerOperations = careersData.map((career) => ({
      updateOne: {
        filter: { name: career.name },
        update: { $set: career },
        upsert: true,
      },
    }));
    await Career.bulkWrite(careerOperations);
    const totalCareers = await Career.countDocuments();
    console.log(`Successfully seeded/updated careers! Total careers in database: ${totalCareers}`);

    console.log('Seeding/upserting assessment questions...');
    const questionOperations = assessmentQuestionsData.map((question) => ({
      updateOne: {
        filter: { order: question.order },
        update: { $set: question },
        upsert: true,
      },
    }));
    await AssessmentQuestion.bulkWrite(questionOperations);
    const totalQuestions = await AssessmentQuestion.countDocuments();
    console.log(`Successfully seeded/updated assessment questions! Total questions in database: ${totalQuestions}`);

    console.log('Database seeding completed successfully!');
    if (memoryServer) {
      await memoryServer.stop();
    }
    process.exit(0);
  } catch (error) {
    console.error('Error during database seed:', error);
    process.exit(1);
  }
}

if (require.main === module) {
  seedDatabase();
}

